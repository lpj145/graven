//! Codegen: snapshots of the generated Rust for the 5 schemas (+ `edge`) plus structural checks on
//! the emitted text. The behavioural gates (the `graven-schemas` tests — layout, roundtrip,
//! evolution, verified, mutation — edge cases and conformance vectors) live where the
//! generated code is compiled: `crates/graven-schemas/tests`, `crates/graven-codegen-tests` and
//! `crates/graven-conformance/tests/generated.rs`. Since Task 8 there is no hand-written
//! reference any more: these snapshots are what guards the generated text against regressions.
//!
//! `GRAVEN_BLESS=1 cargo test -p graven-compiler --test codegen` rewrites the snapshots.

use std::path::PathBuf;
use graven_compiler::codegen::{generate, generate_with_source};
use graven_compiler::lock::{Lock, lock_from_ir, read_lock, reserved_types};
use graven_compiler::*;

fn crates_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("..")
}

/// `(snapshot name, schema path relative to crates/)`.
const SCHEMAS: &[(&str, &str)] = &[
    ("bank", "graven-schemas/schemas/bank.graven"),
    ("game", "graven-schemas/schemas/game.graven"),
    ("iot", "graven-schemas/schemas/iot.graven"),
    ("stream", "graven-schemas/schemas/stream.graven"),
    ("conformance", "graven-conformance/schemas/conformance.graven"),
    // Edge cases (required pointers, defaults, nested scalar-only tables, …).
    ("edge", "graven-codegen-tests/schemas/edge.graven"),
];

/// Parse + check against the committed lock (`<schema>.lock`), which must be current.
fn load(rel: &str) -> (Ir, Lock) {
    let path = crates_dir().join(rel);
    let src = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let lock_path = PathBuf::from(format!("{}.lock", path.display()));
    let lock = read_lock(&lock_path).unwrap_or_else(|e| panic!("{e}")).unwrap_or_else(|| panic!("{} missing", lock_path.display()));
    let ast = parse(&src).unwrap_or_else(|e| panic!("{rel}: {e}"));
    let ir = check(&ast, &reserved_types(&lock)).unwrap_or_else(|d| panic!("{rel}: {d:?}"));
    assert_eq!(lock_from_ir(&ir, Some(&lock)), lock, "{}: lock desatualizado", lock_path.display());
    (ir, lock)
}

fn file_name(rel: &str) -> &str {
    rel.rsplit('/').next().unwrap()
}

#[test]
fn snapshots() {
    let bless = std::env::var_os("GRAVEN_BLESS").is_some_and(|v| v == "1");
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/snapshots");
    std::fs::create_dir_all(&dir).unwrap();
    let mut failed = Vec::new();
    for (name, rel) in SCHEMAS {
        let (ir, lock) = load(rel);
        let got = generate_with_source(&ir, &lock, file_name(rel));
        let snap = dir.join(format!("{name}.rs"));
        match std::fs::read_to_string(&snap) {
            Ok(want) if !bless => {
                if want != got {
                    failed.push(snap.display().to_string());
                }
            }
            // First run (or bless): write the snapshot, to be reviewed by hand.
            _ => {
                std::fs::write(&snap, &got).unwrap();
                eprintln!("snapshot written: {}", snap.display());
            }
        }
    }
    assert!(failed.is_empty(), "snapshots differ (run with GRAVEN_BLESS=1 and review the diff): {failed:?}");
}

#[test]
fn deterministic() {
    for (_, rel) in SCHEMAS {
        let (ir, lock) = load(rel);
        assert_eq!(generate(&ir, &lock), generate(&ir, &lock), "{rel}");
    }
}

#[test]
fn header_and_no_inner_attributes() {
    for (_, rel) in SCHEMAS {
        let (ir, lock) = load(rel);
        let out = generate_with_source(&ir, &lock, file_name(rel));
        let first = out.lines().next().unwrap();
        assert_eq!(first, format!("// @generated by gravenc from {} — do not edit", file_name(rel)));
        assert!(!out.contains("#!["), "{rel}: code included via include! cannot have inner attributes");
        // `generate` (without a file name) uses the namespace.
        let out2 = generate(&ir, &lock);
        assert_eq!(out2.lines().next().unwrap(), format!("// @generated by gravenc from {} — do not edit", ir.namespace));
    }
}

/// Every `unsafe` block is preceded by a `// SAFETY:` comment, sits in an item with
/// `#[allow(unsafe_code)]`, and the sentinel used to carry the comment through
/// prettyplease is gone.
#[test]
fn every_unsafe_has_safety_comment() {
    for (_, rel) in SCHEMAS {
        let (ir, lock) = load(rel);
        let out = generate(&ir, &lock);
        assert!(!out.contains("__graven_safety"), "{rel}: a SAFETY sentinel was left over");
        let lines: Vec<&str> = out.lines().collect();
        for (i, l) in lines.iter().enumerate() {
            if !l.contains("unsafe {") {
                continue;
            }
            // Walk back over the comment block right above.
            let mut j = i;
            let mut saw = false;
            while j > 0 && lines[j - 1].trim_start().starts_with("//") {
                j -= 1;
                saw |= lines[j].trim_start().starts_with("// SAFETY:");
            }
            assert!(saw, "{rel}:{}: `unsafe` without `// SAFETY:` right above:\n{l}", i + 1);
            // The enclosing fn carries `#[allow(unsafe_code)]`.
            let fn_line = (0..i).rev().find(|&k| lines[k].contains(" fn ")).expect("fn acima");
            assert!(
                lines[fn_line - 1].contains("#[allow(unsafe_code)]") || lines[fn_line - 2].contains("#[allow(unsafe_code)]"),
                "{rel}:{}: fn with `unsafe` without #[allow(unsafe_code)]",
                fn_line + 1
            );
        }
    }
}

#[test]
fn schema_id_comes_from_lock() {
    let (ir, mut lock) = load("graven-schemas/schemas/bank.graven");
    let t = lock.tables.iter_mut().find(|t| t.name == "Transaction").unwrap();
    t.schema_id = "0x0123456789abcdef".to_string();
    let out = generate(&ir, &lock);
    assert!(out.contains("0x0123456789abcdef"), "SCHEMA_ID must come from the lock");
}

#[test]
fn module_level_schema_ids() {
    // bank: Entry is referenced by Transaction ⇒ Transaction is the single root.
    let (ir, lock) = load("graven-schemas/schemas/bank.graven");
    let out = generate(&ir, &lock);
    assert!(out.contains("pub const ENTRY_SCHEMA_ID: u64"));
    assert!(out.contains("pub const TRANSACTION_SCHEMA_ID: u64"));
    // No module-level alias: the inferred root would move silently when a new table
    // references the old one.
    assert!(!out.lines().any(|l| l.starts_with("pub const SCHEMA_ID")), "no module-level SCHEMA_ID");
}

#[test]
fn reserved_field_generates_nothing() {
    let (ir, lock) = load("graven-conformance/schemas/conformance.graven");
    let out = generate(&ir, &lock);
    assert!(!out.contains("_reserved_"), "a reserved field generates nothing");
    assert!(!out.contains("RESERVED"), "a reserved field generates no consts");
}

