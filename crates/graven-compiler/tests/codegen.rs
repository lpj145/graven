/// Safety requirement: the file says, right in its header, that it must be alone in its own
/// module (code in the same module can construct `XVerified(...)` directly).
#[test]
fn header_says_own_module() {
    let (ir, lock) = load("graven-schemas/schemas/bank.graven");
    let out = generate_with_source(&ir, &lock, "bank.graven");
    let second = out.lines().nth(1).unwrap();
    assert!(second.starts_with("// Include this file alone in its own module"), "{second}");
    assert!(out.lines().take(4).any(|l| l.contains("mod x { include!(...); }")));
}

/// Type names whose module is a keyword (`Type` ⇒ `r#type`) and names that
/// resemble the prelude (`FnOnce`, `Option`) generate valid Rust.
#[test]
fn keyword_module_and_prelude_names() {
    let src = "namespace t; table Type { a @0: u32; } table FnOnce { t @0: Type?; xs @1: [Type]?; } struct Option { a: u8 }";
    let ir = check(&parse(src).unwrap(), &|_: &str, _: u16| None).unwrap();
    let lock = lock_from_ir(&ir, None);
    let out = generate(&ir, &lock);
    assert!(out.contains("pub mod r#type {"), "raw module");
    assert!(out.contains("::core::ops::FnOnce("), "FnOnce absoluto");
    assert!(!out.contains(" FnOnce(&mut"), "FnOnce without a path");
}

/// An identifier named like the SAFETY sentinel does not break the generator.
#[test]
fn identifier_named_like_safety_sentinel() {
    let src = "namespace __graven_safety.v1;\nenum E : u8 { __graven_safety = 1 }\ntable T { __graven_safety @0: u32; e @1: E; }\n";
    let schema = parse(src).unwrap();
    let ir = check(&schema, &|_: &str, _: u16| None).unwrap();
    let lock = lock_from_ir(&ir, None);
    let out = generate(&ir, &lock);
    assert!(!out.contains("__graven_safety!("));
}
