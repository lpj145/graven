/// Options controlling RPC code generation (`--side client`, `--side server`).
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct GenOptions {
    pub client: bool,
    pub server: bool,
}

/// Formatted Rust for `include!`, with the header `// @generated by gravenc from <namespace> —
/// do not edit`. Same as [`generate_with_source`] with the namespace in place of the file.
///
/// # Panics
/// If the lock lacks some table of the IR (the caller guarantees that the lock matches the IR:
/// `lock_from_ir(ir, Some(lock)) == *lock`), or if the lock's `schema_id` is invalid.
pub fn generate(ir: &Ir, lock: &Lock) -> String {
    generate_with_source(ir, lock, &ir.namespace)
}

/// Like [`generate`], with `source` (the `.graven` file name) in the header.
pub fn generate_with_source(ir: &Ir, lock: &Lock, source: &str) -> String {
    generate_with_options(ir, lock, source, GenOptions::default())
}

/// Like [`generate_with_source`], with explicit codegen options (`--side`).
pub fn generate_with_options(ir: &Ir, lock: &Lock, source: &str, opts: GenOptions) -> String {
    let tokens = items(ir, lock, opts);
    let file: syn::File = syn::parse2(tokens).unwrap_or_else(|e| panic!("codegen produced invalid Rust: {e}"));
    finish(&prettyplease::unparse(&file), source)
}

/// Header lines after `@generated`: the own-module requirement.
const HEADER_SAFETY: &str = "// Include this file alone in its own module: `mod x { include!(...); }` — code in the\n\
// same module could break the safety of the verified views (by constructing `XVerified(...)`\n\
// without `verify()`).\n";

/// Header + replacement of the `__graven_safety!("…");` sentinels with `// SAFETY:` comments.
fn finish(formatted: &str, source: &str) -> String {
    let mut out = format!("// @generated by gravenc from {source} — do not edit\n");
    out.push_str(HEADER_SAFETY);
    let lines: Vec<&str> = formatted.lines().collect();
    let mut i = 0;
    while i < lines.len() {
        let line = lines[i];
        let t = line.trim_start();
        let indent = &line[..line.len() - t.len()];
        // prettyplease prints the sentinel on one line or as `__graven_safety!(` / `"…"` / `);`.
        let text = if let Some(rest) = t.strip_prefix("__graven_safety!(\"") {
            rest.strip_suffix("\");").unwrap_or_else(|| panic!("malformed SAFETY sentinel: {line}"))
        } else if t == "__graven_safety!(" {
            let lit = lines.get(i + 1).map(|l| l.trim()).unwrap_or_default();
            assert_eq!(lines.get(i + 2).map(|l| l.trim()), Some(");"), "malformed SAFETY sentinel near: {line}");
            i += 2;
            lit.strip_prefix('"').and_then(|l| l.strip_suffix('"')).unwrap_or_else(|| panic!("malformed SAFETY sentinel: {lit}"))
        } else {
            out.push_str(line);
            out.push('\n');
            i += 1;
            continue;
        };
        for (k, chunk) in wrap(text, 92).into_iter().enumerate() {
            out.push_str(indent);
            out.push_str(if k == 0 { "// SAFETY: " } else { "// " });
            out.push_str(&chunk);
            out.push('\n');
        }
        i += 1;
    }
    // Only the call form: a schema identifier may be named `__graven_safety`.
    assert!(!out.contains("__graven_safety!("), "SAFETY sentinel not converted");
    out
}

/// Wraps `s` into lines of up to ~`width` columns (by word).
fn wrap(s: &str, width: usize) -> Vec<String> {
    let mut lines = Vec::new();
    let mut cur = String::new();
    for w in s.split_whitespace() {
        if !cur.is_empty() && cur.len() + 1 + w.len() > width {
            lines.push(std::mem::take(&mut cur));
        }
        if !cur.is_empty() {
            cur.push(' ');
        }
        cur.push_str(w);
    }
    lines.push(cur);
    lines
}

/// `// SAFETY:` comment sentinel (see the module docs). `text` cannot contain `"` or `\`.
fn safety(text: &str) -> TokenStream {
    assert!(!text.contains(['"', '\\']), "SAFETY text with quote/backslash: {text}");
    let lit = Literal::string(text);
    quote! { __graven_safety!(#lit); }
}

fn items(ir: &Ir, lock: &Lock, opts: GenOptions) -> TokenStream {
    let cx = Cx { ir, lock };
    let mut out = TokenStream::new();
    out.extend(cx.module_schema_ids());
    // Imported types (`origin` set) are generated by their own schema and referred to by path.
    for e in ir.enums.iter().filter(|e| e.origin.is_none()) {
        out.extend(cx.enum_def(e));
    }
    for s in ir.structs.iter().filter(|s| s.origin.is_none()) {
        out.extend(cx.struct_def(s));
    }
    for u in ir.unions.iter().filter(|u| u.origin.is_none()) {
        out.extend(cx.union_def(u));
    }
    for (i, _) in ir.tables.iter().enumerate().filter(|(_, t)| t.origin.is_none()) {
        let t = cx.table(TableId(i));
        out.extend(cx.layout_mod(&t));
        out.extend(cx.reader(&t));
        out.extend(cx.view(&t));
        out.extend(cx.writer(&t));
    }
    out.extend(cx.checks_trait());
    out.extend(cx.rpc_items(opts));
    out
}

