//! Codegen: [`Ir`] + [`Lock`] → Rust (via `quote` → `syn` → `prettyplease`).
//!
//! The emitted code is the pattern frozen by hand in `graven-schemas` and documented
//! in `graven::rt` ("Generated pattern" and "Invariants for the code generator"). Each
//! table generates:
//!
//! - `mod <table_snake>` with the layout consts (`FIXED_LEN`, offsets, `*_BIT`,
//!   `PTR_SLOTS`);
//! - the reader `X<'a>` (`read`): `<X>_REQ`/`<X>_MASK`, `FromTable`, accessors, `verify`
//!   `#[inline]`, `read`/`verified`/`verified_with`/`from_bytes`, `SCHEMA_ID` (from the lock);
//! - the view `XVerified<'a>` (`view`): explicit accessors + `reader()`;
//! - the writer `XW<'b>` (`write`), the element descriptor `XE` and, for a table of
//!   scalars only, `XListW`.
//!
//! Enum ⇒ `enum X { …, Unknown(base) }` + `from_raw`/`to_raw` + `Default` + `Le`; struct
//! ⇒ `struct X` + `Le`; union ⇒ `enum U<'a>` (reader) and `enum UVerified<'a>` (view), with
//! an `Unknown(u16)` that is not descended into.
//!
//! The generated file is meant for `include!` inside a module: items only, no inner
//! attributes, and every path is absolute (`::graven::…`, `::core::…`), so it does not depend
//! on the includer's `use`s. The including module should have `#![deny(unsafe_code)]`; each item
//! that calls an `unsafe` runtime function carries `#[allow(unsafe_code)]`.
//!
//! # Safety: the generated code must be the only content of its module
//!
//! The view `XVerified<'a>(X<'a>)` reads strings without revalidating UTF-8 (`str_unchecked`); it
//! is sound because it is only constructed after `verify()`. The tuple field is private, but
//! Rust privacy is **per module**: *safe* code written in the same module as the
//! `include!` could write `XVerified(X::read(buf)?)` without verifying and cause UB. Hence:
//!
//! ```ignore
//! pub mod bank {
//!     include!(concat!(env!("OUT_DIR"), "/bank.rs")); // nothing else in this module
//! }
//! ```
//!
//! The header of the generated file repeats the warning.
//!
//! **`// SAFETY:` comments**: `prettyplease` drops comments, so the generator emits a
//! sentinel statement `__graven_safety!("…");` before each `unsafe` block and, after
//! formatting, replaces each sentinel line with `// SAFETY: …` lines at the same
//! indentation (`finish`). The result is a real comment right above the
//! `unsafe`, as in hand-written code.

