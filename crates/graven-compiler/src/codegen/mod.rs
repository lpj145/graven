/// `RootV2` ⇒ `root_v2`, `HTTPServer` ⇒ `http_server`, `snake` ⇒ `snake`.
pub fn snake(s: &str) -> String {
    let cs: Vec<char> = s.chars().collect();
    let mut out = String::new();
    for (i, &c) in cs.iter().enumerate() {
        if c.is_ascii_uppercase() {
            let prev = i.checked_sub(1).map(|j| cs[j]);
            let next = cs.get(i + 1).copied();
            let boundary = match prev {
                None | Some('_') => false,
                Some(p) if p.is_ascii_lowercase() || p.is_ascii_digit() => true,
                Some(p) if p.is_ascii_uppercase() => next.is_some_and(|n| n.is_ascii_lowercase()),
                _ => false,
            };
            if boundary {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

fn upper(s: &str) -> String {
    snake(s).to_ascii_uppercase()
}

const KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in", "let",
    "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "static", "struct", "trait", "true", "type",
    "unsafe", "use", "where", "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen",
];

/// Identifier; a keyword becomes `r#name`.
fn ident(s: &str) -> Ident {
    if KEYWORDS.contains(&s) { Ident::new_raw(s, Span::call_site()) } else { Ident::new(s, Span::call_site()) }
}

fn lit_u16(v: u16) -> Literal {
    Literal::u16_unsuffixed(v)
}

fn lit_u8(v: u8) -> Literal {
    Literal::u8_unsuffixed(v)
}

// ------------------------------------------------------------------ model

struct Cx<'a> {
    ir: &'a Ir,
    lock: &'a Lock,
}

/// A table plus the names the generated code uses for it.
struct T<'a> {
    def: &'a Table,
    /// `Transaction`
    name: Ident,
    /// `transaction` (layout consts module)
    m: Ident,
    /// `TRANSACTION`
    up: String,
    /// Non-reserved fields with their layout.
    fields: Vec<F<'a>>,
}

/// One non-reserved field.
struct F<'a> {
    name: &'a str,
    ty: &'a Ty,
    presence: &'a Presence,
    rules: &'a FieldRules,
    slot: Option<u16>,
    bit: Option<(u16, u8)>,
    /// accessor / setter name
    id: Ident,
    /// `NOTE` (slot offset const; `None` for bool)
    off: Option<Ident>,
    /// `NOTE_BIT`
    bitc: Option<Ident>,
}

impl<'a> Cx<'a> {
    fn table(&self, id: TableId) -> T<'a> {
        let def = &self.ir.tables[id.0];
        let fields = def
            .fields
            .iter()
            .zip(&def.layout.fields)
            .filter(|(f, _)| !matches!(f.presence, Presence::Reserved { .. }))
            .map(|(f, l)| F {
                name: &f.name,
                ty: &f.ty,
                presence: &f.presence,
                rules: &f.rules,
                slot: l.slot,
                bit: l.presence,
                id: ident(&f.name),
                off: l.slot.map(|_| format_ident!("{}", upper(&f.name))),
                bitc: l.presence.map(|_| format_ident!("{}_BIT", upper(&f.name))),
            })
            .collect();
        T { def, name: format_ident!("{}", def.name), m: ident(&snake(&def.name)), up: upper(&def.name), fields }
    }

    /// Path of the generated type `<name><suffix>`: `Name` here, or
    /// `super::<namespace segment>::Name` for a type imported from another schema, whose
    /// module is a sibling of this one.
    fn type_path(&self, name: &str, origin: &Option<String>, suffix: &str) -> TokenStream {
        let n = format_ident!("{}{}", base_name(name), suffix);
        match origin {
            None => quote!(#n),
            Some(ns) => {
                let m = ident(ns.rsplit('.').next().unwrap_or(ns));
                quote!(super::#m::#n)
            }
        }
    }

    fn table_path(&self, id: TableId, suffix: &str) -> TokenStream {
        let t = &self.ir.tables[id.0];
        self.type_path(&t.name, &t.origin, suffix)
    }

    fn union_path(&self, id: UnionId, suffix: &str) -> TokenStream {
        let u = &self.ir.unions[id.0];
        self.type_path(&u.name, &u.origin, suffix)
    }

    fn table_name(&self, id: TableId) -> TokenStream {
        self.table_path(id, "")
    }

    /// The layout-consts module of a table (`entry`, or `super::common::address`).
    fn table_mod(&self, id: TableId) -> TokenStream {
        let t = &self.ir.tables[id.0];
        let m = ident(&snake(base_name(&t.name)));
        match &t.origin {
            None => quote!(#m),
            Some(ns) => {
                let s = ident(ns.rsplit('.').next().unwrap_or(ns));
                quote!(super::#s::#m)
            }
        }
    }

    fn all_scalar(&self, id: TableId) -> bool {
        self.ir.tables[id.0].all_scalar
    }

    fn schema_id(&self, t: &Table) -> Literal {
        let lt = self
            .lock
            .tables
            .iter()
            .find(|l| l.name == t.name)
            .unwrap_or_else(|| panic!("lock lacks table `{}` (run `gravenc update`)", t.name));
        let hex = lt.schema_id.strip_prefix("0x").unwrap_or_else(|| panic!("invalid schema_id: {}", lt.schema_id));
        let v = u64::from_str_radix(hex, 16).unwrap_or_else(|_| panic!("invalid schema_id: {}", lt.schema_id));
        format!("{:#018x}", v).parse::<Literal>().unwrap()
    }

    /// Rust type of an inline (fixed-size) value: scalar, bool, enum, struct.
    fn inline_ty(&self, ty: &Ty) -> TokenStream {
        match ty {
            Ty::Scalar(p) => prim(*p),
            Ty::Bool => quote!(bool),
            Ty::Enum(id) => {
                let e = &self.ir.enums[id.0];
                self.type_path(&e.name, &e.origin, "")
            }
            Ty::Struct(id) => {
                let s = &self.ir.structs[id.0];
                self.type_path(&s.name, &s.origin, "")
            }
            _ => unreachable!("inline_ty of a pointer type"),
        }
    }

    /// Wire type stored in a table slot (enum ⇒ its base).
    fn slot_ty(&self, ty: &Ty) -> TokenStream {
        match ty {
            Ty::Enum(id) => prim(self.ir.enums[id.0].base),
            _ => self.inline_ty(ty),
        }
    }

    /// Default literal for a scalar/enum slot (wire type).
    fn default_lit(&self, ty: &Ty, v: &Value) -> TokenStream {
        match (ty, v) {
            (Ty::Scalar(p), Value::Int(i)) if p.is_float() => float_lit(*p, *i as f64),
            (Ty::Scalar(p), Value::Float(f)) => float_lit(*p, *f),
            (Ty::Scalar(p), Value::Int(i)) => int_lit(*p, *i),
            (Ty::Scalar(p), Value::UInt(u)) => uint_lit(*p, *u),
            (Ty::Enum(id), Value::Enum { raw, .. }) => int_lit(self.ir.enums[id.0].base, *raw as i128),
            (Ty::Enum(id), Value::Int(i)) => int_lit(self.ir.enums[id.0].base, *i),
            (Ty::Bool, Value::Bool(b)) => quote!(#b),
            _ => panic!("default {v:?} incompatible with {}", self.ir.ty_name(ty)),
        }
    }

    // ------------------------------------------------------- top-level items

    /// `<TABLE>_SCHEMA_ID` for every table. No module-level `SCHEMA_ID` alias: a "root"
    /// inferred from references would silently move to a new table that references the
    /// old root (compat-allowed), re-pointing client dispatch code.
    fn module_schema_ids(&self) -> TokenStream {
        let mut out = TokenStream::new();
        for t in self.ir.tables.iter().filter(|t| t.origin.is_none()) {
            let n = format_ident!("{}", t.name);
            let c = format_ident!("{}_SCHEMA_ID", upper(&t.name));
            let doc = format!(" Schema id of `{}.{}` (envelope header); same as [`{}::SCHEMA_ID`].", self.ir.namespace, t.name, t.name);
            out.extend(quote! {
                #[doc = #doc]
                pub const #c: u64 = #n::SCHEMA_ID;
            });
        }
        out
    }

    fn enum_def(&self, e: &Enum) -> TokenStream {
        let n = format_ident!("{}", e.name);
        let base = prim(e.base);
        let size = Literal::usize_unsuffixed(e.base.size() as usize);
        let vars: Vec<Ident> = e.values.iter().map(|(v, _)| ident(v)).collect();
        let vdocs: Vec<TokenStream> = e.values.iter().map(|(v, _)| user_doc_only(self.ir, &format!("{}.{v}", e.name))).collect();
        let raws: Vec<Literal> = e.values.iter().map(|(_, r)| Literal::u32_unsuffixed(*r)).collect();
        let udoc = user_doc(self.ir, &e.name);
        let doc = format!(" Enum `{}` (base `{}`); a value outside the variants ⇒ `Unknown(raw)`.", e.name, e.base.name());
        quote! {
            #udoc
            #[doc = #doc]
            #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
            pub enum #n {
                #(#vdocs #vars,)*
                Unknown(#base),
            }
            impl #n {
                #[inline]
                pub fn from_raw(v: #base) -> Self {
                    match v {
                        #(#raws => #n::#vars,)*
                        x => #n::Unknown(x),
                    }
                }
                #[inline]
                pub fn to_raw(self) -> #base {
                    match self {
                        #(#n::#vars => #raws,)*
                        #n::Unknown(x) => x,
                    }
                }
            }
            impl ::core::default::Default for #n {
                /// The raw value 0.
                #[inline]
                fn default() -> Self {
                    #n::from_raw(0)
                }
            }
            impl ::graven::Le for #n {
                const SIZE: usize = #size;
                #[inline(always)]
                fn read_le(b: &[u8]) -> Self {
                    #n::from_raw(<#base as ::graven::Le>::read_le(b))
                }
                #[inline(always)]
                fn write_le(self, out: &mut [u8]) {
                    ::graven::Le::write_le(self.to_raw(), out)
                }
            }
        }
    }

    fn struct_def(&self, s: &Struct) -> TokenStream {
        let n = format_ident!("{}", s.name);
        let size = Literal::usize_unsuffixed(s.size as usize);
        let mut decls = Vec::new();
        let mut reads = Vec::new();
        let mut writes = Vec::new();
        let mut at = 0usize;
        let mut eq = true;
        for (fname, ty) in &s.fields {
            let f = ident(fname);
            let rty = self.inline_ty(ty);
            let w = self.ir.inline_size(ty).expect("struct field has a fixed size") as usize;
            let (a, b) = (Literal::usize_unsuffixed(at), Literal::usize_unsuffixed(at + w));
            let fdoc = user_doc_only(self.ir, &format!("{}.{fname}", s.name));
            decls.push(quote!(#fdoc pub #f: #rty));
            reads.push(quote!(#f: <#rty as ::graven::Le>::read_le(&b[#a..#b])));
            writes.push(quote!(::graven::Le::write_le(self.#f, &mut out[#a..#b]);));
            at += w;
            eq &= !self.has_float(ty);
        }
        assert_eq!(at, s.size as usize, "struct {}: size does not match the fields", s.name);
        let derive_eq = if eq { quote!(Eq,) } else { quote!() };
        let (bn, on) = if s.fields.is_empty() { (format_ident!("_b"), format_ident!("_out")) } else { (format_ident!("b"), format_ident!("out")) };
        let doc = format!(" Frozen struct `{}`: {} bytes, never evolves.", s.name, s.size);
        let udoc = user_doc(self.ir, &s.name);
        quote! {
            #udoc
            #[doc = #doc]
            #[derive(Debug, Clone, Copy, PartialEq, #derive_eq Default)]
            pub struct #n {
                #(#decls,)*
            }
            impl ::graven::Le for #n {
                const SIZE: usize = #size;
                #[inline(always)]
                fn read_le(#bn: &[u8]) -> Self {
                    #n { #(#reads,)* }
                }
                #[inline(always)]
                fn write_le(self, #on: &mut [u8]) {
                    #(#writes)*
                }
            }
        }
    }

    fn has_float(&self, ty: &Ty) -> bool {
        match ty {
            Ty::Scalar(p) => p.is_float(),
            Ty::Struct(id) => self.ir.structs[id.0].fields.iter().any(|(_, t)| self.has_float(t)),
            _ => false,
        }
    }

    fn union_def(&self, u: &Union) -> TokenStream {
        let n = format_ident!("{}", u.name);
        let nv = format_ident!("{}Verified", u.name);
        let vars: Vec<Ident> = u.variants.iter().map(|(v, _, _)| ident(v)).collect();
        let tys: Vec<TokenStream> = u.variants.iter().map(|(_, _, t)| self.table_path(*t, "")).collect();
        let tysv: Vec<TokenStream> = u.variants.iter().map(|(_, _, t)| self.table_path(*t, "Verified")).collect();
        let vdocs: Vec<TokenStream> =
            u.variants.iter().map(|(v, _, _)| user_doc_only(self.ir, &format!("{}.{v}", u.name))).collect();
        let udoc = user_doc(self.ir, &u.name);
        let doc = format!(
            " Union `{}` as read by the checked reader. Unknown tag ⇒ `Unknown(tag)` (the target is not visited).",
            u.name
        );
        let docv = format!(
            " Union `{}` in a verified message. Unknown tag ⇒ `Unknown(tag)`: `verify` did not descend into it, so the view does not either.",
            u.name
        );
        quote! {
            #udoc
            #[doc = #doc]
            #[derive(Clone, Copy)]
            pub enum #n<'a> {
                #(#vdocs #vars(#tys<'a>),)*
                Unknown(u16),
            }
            #udoc
            #[doc = #docv]
            #[derive(Clone, Copy)]
            pub enum #nv<'a> {
                #(#vdocs #vars(#tysv<'a>),)*
                Unknown(u16),
            }
        }
    }
}

/// `#[doc]` attributes for the schema's documentation of `key`, followed by an empty line
/// so the generated description that follows starts a new paragraph. Empty without docs.
fn user_doc(ir: &Ir, key: &str) -> TokenStream {
    let Some(text) = ir.doc(key) else { return quote!() };
    let lines = text.lines().map(|l| format!(" {l}"));
    quote! { #(#[doc = #lines])* #[doc = ""] }
}

/// Like [`user_doc`], without the trailing empty line (for items with no generated description).
fn user_doc_only(ir: &Ir, key: &str) -> TokenStream {
    let Some(text) = ir.doc(key) else { return quote!() };
    let lines = text.lines().map(|l| format!(" {l}"));
    quote! { #(#[doc = #lines])* }
}

fn prim(p: Prim) -> TokenStream {
    let i = format_ident!("{}", p.name());
    quote!(#i)
}

fn int_lit(p: Prim, v: i128) -> TokenStream {
    let l = match p {
        Prim::U8 => Literal::u8_suffixed(v as u8),
        Prim::U16 => Literal::u16_suffixed(v as u16),
        Prim::U32 => Literal::u32_suffixed(v as u32),
        Prim::U64 => Literal::u64_suffixed(v as u64),
        Prim::U128 => Literal::u128_suffixed(v as u128),
        Prim::I8 => Literal::i8_suffixed(v as i8),
        Prim::I16 => Literal::i16_suffixed(v as i16),
        Prim::I32 => Literal::i32_suffixed(v as i32),
        Prim::I64 => Literal::i64_suffixed(v as i64),
        Prim::I128 => Literal::i128_suffixed(v),
        Prim::F32 | Prim::F64 => return float_lit(p, v as f64),
    };
    // A negative literal is `-` + literal for the parser.
    if v < 0 {
        let s = l.to_string();
        let abs: TokenStream = s.trim_start_matches('-').parse().unwrap();
        // i128::MIN etc.: `-170141183460469231731687303715884105728i128` overflows as a
        // positive literal; use the type's MIN const instead.
        let min = match p {
            Prim::I8 => v == i8::MIN as i128,
            Prim::I16 => v == i16::MIN as i128,
            Prim::I32 => v == i32::MIN as i128,
            Prim::I64 => v == i64::MIN as i128,
            Prim::I128 => v == i128::MIN,
            _ => false,
        };
        if min {
            let t = prim(p);
            return quote!(#t::MIN);
        }
        return quote!(-#abs);
    }
    quote!(#l)
}

fn uint_lit(p: Prim, v: u128) -> TokenStream {
    let l = match p {
        Prim::U8 => Literal::u8_suffixed(v as u8),
        Prim::U16 => Literal::u16_suffixed(v as u16),
        Prim::U32 => Literal::u32_suffixed(v as u32),
        Prim::U64 => Literal::u64_suffixed(v as u64),
        Prim::U128 => Literal::u128_suffixed(v),
        _ => panic!("unsigned default {v} on {}", p.name()),
    };
    quote!(#l)
}

fn float_lit(p: Prim, v: f64) -> TokenStream {
    let neg = v.is_sign_negative();
    let a = v.abs();
    let l = match p {
        Prim::F32 => Literal::f32_suffixed(a as f32),
        _ => Literal::f64_suffixed(a),
    };
    if neg { quote!(-#l) } else { quote!(#l) }
}

/// Wire kind of a field type (`graven_layout`).
fn kind(ir: &Ir, ty: &Ty) -> FieldKind {
    ir.field_kind(ty)
}

/// `ReqMask` bit bytes: every byte holding a required scalar/bool presence bit.
fn req_bytes(t: &T<'_>) -> Vec<u16> {
    let mut v: Vec<u16> = t
        .fields
        .iter()
        .filter(|f| matches!(f.presence, Presence::Required))
        .filter_map(|f| f.bit.map(|b| b.0))
        .collect();
    v.sort_unstable();
    v.dedup();
    v
}

/// `x_<variante_snake>` name of a union variant setter.
fn union_setter(field: &str, variant: &str) -> Ident {
    ident(&format!("{field}_{}", snake(variant)))
}
