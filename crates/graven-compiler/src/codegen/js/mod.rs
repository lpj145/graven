//! Codegen: [`Ir`] + [`Lock`] → JavaScript (`<stem>.js`, no type syntax) with TypeScript
//! declarations (`<stem>.d.ts`). ES2022 modules, no dependencies beyond the runtime that
//! `gravenc` writes next to them (`graven.js` + `graven.d.ts`).
//!
//! Every generated member is described once (`Out::method`, `Out::static_field`, …) and
//! rendered twice: its body into the `.js`, its signature into the `.d.ts`. Keeping a single
//! description per member is what keeps the two files from disagreeing.

mod service;
mod tables;
mod validate;

use std::collections::{BTreeMap, HashSet};
use std::fmt::Write as _;

use super::GenOptions;
use crate::ir::*;
use crate::lock::Lock;

/// The runtime, compiled from `runtime/graven.ts` by `tsc` (see `scripts/ts.sh`).
pub const RUNTIME_JS: &str = include_str!("../../../runtime/graven.js");
/// The runtime's declarations, compiled from `runtime/graven.ts` by `tsc`.
pub const RUNTIME_DTS: &str = include_str!("../../../runtime/graven.d.ts");

/// Header placed at the top of every file `gravenc` writes for `--lang js`.
pub fn header(source: &str) -> String {
    format!("// @generated by gravenc {} from {source} — do not edit\n", env!("CARGO_PKG_VERSION"))
}

/// The runtime files with their header: `(graven.js, graven.d.ts)`.
pub fn runtime_files() -> (String, String) {
    let h = header("the Graven runtime");
    (format!("{h}{RUNTIME_JS}"), format!("{h}{RUNTIME_DTS}"))
}

/// Names a schema type cannot keep in the generated code: TypeScript keywords and globals the
/// generated code relies on. They get a trailing `_`.
const TOP_RESERVED: &[&str] = &[
    "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do",
    "else", "enum", "export", "extends", "false", "finally", "for", "function", "if", "import",
    "in", "instanceof", "new", "null", "return", "super", "switch", "this", "throw", "true", "try",
    "typeof", "var", "void", "while", "with", "as", "implements", "interface", "let", "package",
    "private", "protected", "public", "static", "yield", "await", "any", "boolean", "constructor",
    "declare", "get", "module", "require", "number", "set", "string", "symbol", "type", "from",
    "of", "unknown", "never", "bigint", "object", "undefined", "NaN", "Infinity", "arguments",
    "eval", "globalThis", "Uint8Array", "DataView", "Promise", "ReadableStream", "AsyncIterable",
    "Error", "Iterable", "Iterator", "Record", "Object", "Array", "Checks", "RpcFault",
    "RpcProtocolError",
];

/// Members every JavaScript object already has, plus `then`: an object with a callable `then`
/// is treated as a promise by `await`, which would never settle.
pub(super) const OBJECT_MEMBERS: &[&str] = &[
    "constructor", "then", "toString", "valueOf", "toLocaleString", "hasOwnProperty",
    "isPrototypeOf", "propertyIsEnumerable", "__proto__",
];

/// A set of names already taken in one scope, seeded with [`OBJECT_MEMBERS`] and `extra`.
pub(super) fn member_scope(extra: &[&str]) -> HashSet<String> {
    OBJECT_MEMBERS.iter().chain(extra).map(|s| s.to_string()).collect()
}

/// The generated `.js` and `.d.ts` of one schema.
pub struct JsFiles {
    pub js: String,
    pub dts: String,
}

/// Two outputs written in step.
#[derive(Default)]
pub(super) struct Out {
    pub js: String,
    pub dts: String,
}

/// A parameter of a generated function: typed in `.d.ts`, plain in `.js`.
pub(super) struct Param {
    name: String,
    ty: String,
    optional: bool,
    default: Option<String>,
}

pub(super) fn p(name: &str, ty: impl Into<String>) -> Param {
    Param { name: name.to_string(), ty: ty.into(), optional: false, default: None }
}

/// An optional parameter (`opts?: T` / `opts`).
pub(super) fn p_opt(name: &str, ty: impl Into<String>) -> Param {
    Param { name: name.to_string(), ty: ty.into(), optional: true, default: None }
}

/// A parameter with a default value (`checks?: T` / `checks = {}`).
pub(super) fn p_default(name: &str, ty: impl Into<String>, default: &str) -> Param {
    Param { name: name.to_string(), ty: ty.into(), optional: true, default: Some(default.to_string()) }
}

impl Out {
    /// The same line in both files.
    pub fn both(&mut self, line: &str) {
        self.js.push_str(line);
        self.js.push('\n');
        self.dts.push_str(line);
        self.dts.push('\n');
    }

    pub fn js(&mut self, line: &str) {
        self.js.push_str(line);
        self.js.push('\n');
    }

    pub fn dts(&mut self, line: &str) {
        self.dts.push_str(line);
        self.dts.push('\n');
    }

    pub fn blank(&mut self) {
        self.both("");
    }

    /// A `/** … */` comment, in both files.
    pub fn doc(&mut self, indent: &str, text: Option<&str>) {
        let Some(t) = text else { return };
        let mut s = String::new();
        js_doc(&mut s, indent, Some(t));
        self.js.push_str(&s);
        self.dts.push_str(&s);
    }

    /// A method. `body` lines are indented by the method's indent plus two spaces; a single
    /// line stays on the signature's line.
    pub fn method(&mut self, ind: &str, is_static: bool, name: &str, params: &[Param], ret: &str, body: &[String]) {
        let st = if is_static { "static " } else { "" };
        let js_params: Vec<String> = params
            .iter()
            .map(|p| match &p.default {
                Some(d) => format!("{} = {d}", p.name),
                None => p.name.clone(),
            })
            .collect();
        let dts_params: Vec<String> = params
            .iter()
            .map(|p| format!("{}{}: {}", p.name, if p.optional { "?" } else { "" }, p.ty))
            .collect();
        let _ = writeln!(self.dts, "{ind}{st}{name}({}): {ret};", dts_params.join(", "));
        let head = format!("{ind}{st}{name}({})", js_params.join(", "));
        match body {
            [] => {
                let _ = writeln!(self.js, "{head} {{}}");
            }
            [one] => {
                let _ = writeln!(self.js, "{head} {{ {one} }}");
            }
            many => {
                let _ = writeln!(self.js, "{head} {{");
                for l in many {
                    if l.is_empty() {
                        self.js.push('\n');
                    } else {
                        let _ = writeln!(self.js, "{ind}  {l}");
                    }
                }
                let _ = writeln!(self.js, "{ind}}}");
            }
        }
    }

    /// A public `static readonly` property with a value.
    pub fn static_field(&mut self, ind: &str, name: &str, ty: &str, value: &str) {
        let _ = writeln!(self.js, "{ind}static {name} = {value};");
        let _ = writeln!(self.dts, "{ind}static readonly {name}: {ty};");
    }

    /// A private static property; `value` may span several lines (already indented after the
    /// first one).
    pub fn private_static(&mut self, ind: &str, name: &str, value: &str) {
        let _ = writeln!(self.js, "{ind}static {name} = {value};");
        let _ = writeln!(self.dts, "{ind}private static readonly {name};");
    }
}

/// Generates the `.js` and `.d.ts` of one schema. `imports` maps each imported namespace to
/// the file stem emitted in the same output directory.
pub fn generate_js(
    ir: &Ir,
    lock: &Lock,
    source: &str,
    opts: GenOptions,
    imports: &BTreeMap<String, String>,
) -> JsFiles {
    let used_origins: HashSet<&str> = ir
        .enums
        .iter()
        .filter_map(|e| e.origin.as_deref())
        .chain(ir.structs.iter().filter_map(|s| s.origin.as_deref()))
        .chain(ir.tables.iter().filter_map(|t| t.origin.as_deref()))
        .chain(ir.unions.iter().filter_map(|u| u.origin.as_deref()))
        .collect();

    let mut alias_by_ns = BTreeMap::new();
    let mut ordered_imports: Vec<(String, String)> = Vec::new();
    for (idx, (ns, stem)) in imports.iter().enumerate() {
        if ns == &ir.namespace || !used_origins.contains(ns.as_str()) {
            continue;
        }
        let alias = format!("_imp_{idx}");
        alias_by_ns.insert(ns.clone(), alias.clone());
        ordered_imports.push((alias, stem.clone()));
    }

    let cx = JsCx { ir, lock, imports: alias_by_ns };
    let mut out = Out::default();
    let h = header(source);
    out.js.push_str(&h);
    out.dts.push_str(&h);
    out.both("import * as _graven from \"./graven.js\";");
    for (alias, stem) in &ordered_imports {
        out.both(&format!("import * as {alias} from \"./{stem}.js\";"));
    }
    out.blank();

    for e in ir.enums.iter().filter(|e| e.origin.is_none()) {
        cx.emit_enum(&mut out, e);
    }
    for s in ir.structs.iter().filter(|s| s.origin.is_none()) {
        cx.emit_struct(&mut out, s);
    }
    for u in ir.unions.iter().filter(|u| u.origin.is_none()) {
        cx.emit_union(&mut out, u);
    }
    for (i, _) in ir.tables.iter().enumerate().filter(|(_, t)| t.origin.is_none()) {
        cx.emit_table(&mut out, TableId(i));
    }
    cx.emit_checks_interface(&mut out);
    cx.emit_services(&mut out, opts);
    // An empty module is still a module.
    out.js.push_str("export {};\n");
    JsFiles { js: out.js, dts: out.dts }
}

pub(super) struct JsCx<'a> {
    pub ir: &'a Ir,
    pub lock: &'a Lock,
    pub imports: BTreeMap<String, String>,
}

impl<'a> JsCx<'a> {
    pub(super) fn top_ident(&self, raw: &str) -> String {
        let mut s = raw.to_string();
        if TOP_RESERVED.contains(&s.as_str()) {
            s.push('_');
        }
        s
    }

    pub(super) fn type_path(&self, name: &str, origin: &Option<String>, suffix: &str) -> String {
        let base = format!("{}{}", base_name(name), suffix);
        let ident = self.top_ident(&base);
        match origin {
            None => ident,
            Some(ns) => {
                let alias = self
                    .imports
                    .get(ns)
                    .unwrap_or_else(|| panic!("missing JS import mapping for namespace `{ns}`"));
                format!("{alias}.{ident}")
            }
        }
    }

    pub(super) fn table_path(&self, id: TableId, suffix: &str) -> String {
        let t = &self.ir.tables[id.0];
        self.type_path(&t.name, &t.origin, suffix)
    }

    pub(super) fn union_path(&self, id: UnionId, suffix: &str) -> String {
        let u = &self.ir.unions[id.0];
        self.type_path(&u.name, &u.origin, suffix)
    }

    pub(super) fn struct_codec(&self, id: StructId) -> String {
        let s = &self.ir.structs[id.0];
        let cname = format!("_codec_{}", base_name(&s.name));
        match &s.origin {
            None => cname,
            Some(ns) => {
                let alias = self
                    .imports
                    .get(ns)
                    .unwrap_or_else(|| panic!("missing JS import mapping for namespace `{ns}`"));
                format!("{alias}.{cname}")
            }
        }
    }

    pub(super) fn schema_id_lit(&self, t: &Table) -> String {
        let lt = self
            .lock
            .tables
            .iter()
            .find(|l| l.name == t.name)
            .unwrap_or_else(|| panic!("lock lacks table `{}` (run `gravenc update`)", t.name));
        let hex = lt.schema_id.strip_prefix("0x").unwrap_or_else(|| panic!("invalid schema_id: {}", lt.schema_id));
        let v = u64::from_str_radix(hex, 16).unwrap_or_else(|_| panic!("invalid schema_id: {}", lt.schema_id));
        format!("{v:#018x}n")
    }

    pub(super) fn inline_ty(&self, ty: &Ty) -> String {
        match ty {
            Ty::Scalar(p) => prim_ty(*p).to_string(),
            Ty::Bool => "boolean".to_string(),
            Ty::Enum(id) => {
                let e = &self.ir.enums[id.0];
                self.type_path(&e.name, &e.origin, "")
            }
            Ty::Struct(id) => {
                let s = &self.ir.structs[id.0];
                self.type_path(&s.name, &s.origin, "")
            }
            _ => unreachable!("inline_ty on non-inline type"),
        }
    }

    pub(super) fn codec(&self, ty: &Ty) -> String {
        match ty {
            Ty::Scalar(p) => prim_codec(*p).to_string(),
            Ty::Bool => "_graven.leBool".to_string(),
            Ty::Enum(id) => prim_codec(self.ir.enums[id.0].base).to_string(),
            Ty::Struct(id) => self.struct_codec(*id),
            _ => unreachable!("codec on non-inline type"),
        }
    }

    pub(super) fn fallback(&self, ty: &Ty) -> String {
        match ty {
            Ty::Scalar(p) if is_bigint(*p) => "0n".to_string(),
            Ty::Scalar(_) | Ty::Enum(_) => "0".to_string(),
            Ty::Bool => "false".to_string(),
            Ty::Struct(id) => {
                let s = &self.ir.structs[id.0];
                if s.fields.is_empty() {
                    "{}".to_string()
                } else {
                    let fields: Vec<String> =
                        s.fields.iter().map(|(n, fty)| format!("{n}: {}", self.fallback(fty))).collect();
                    format!("{{ {} }}", fields.join(", "))
                }
            }
            _ => unreachable!("fallback on non-inline type"),
        }
    }

    pub(super) fn default_lit(&self, ty: &Ty, v: &Value) -> String {
        match (ty, v) {
            (Ty::Scalar(p), Value::Int(i)) if p.is_float() => fmt_float(*p, *i as f64),
            (Ty::Scalar(p), Value::Float(f)) => fmt_float(*p, *f),
            (Ty::Scalar(p), Value::Int(i)) => {
                if is_bigint(*p) { format!("{i}n") } else { format!("{i}") }
            }
            (Ty::Scalar(p), Value::UInt(u)) => {
                if is_bigint(*p) { format!("{u}n") } else { format!("{u}") }
            }
            (Ty::Enum(_), Value::Enum { raw, .. }) => format!("{raw}"),
            (Ty::Enum(_), Value::Int(i)) => format!("{i}"),
            (Ty::Bool, Value::Bool(b)) => format!("{b}"),
            _ => panic!("default {v:?} incompatible with {}", self.ir.ty_name(ty)),
        }
    }

    fn emit_enum(&self, out: &mut Out, e: &Enum) {
        let name = self.top_ident(&e.name);
        let mut used = member_scope(&["name"]);
        let keys: Vec<(String, &String, String)> =
            e.values.iter().map(|(vname, raw)| (escape_with(vname, &mut used), vname, raw.to_string())).collect();

        let mut d = String::new();
        js_doc(&mut d, "", self.ir.doc(&e.name));
        out.dts.push_str(&d);
        out.dts(&format!("export type {name} = number;"));
        out.doc("", self.ir.doc(&e.name));
        out.js(&format!("export const {name} = Object.freeze({{"));
        out.dts(&format!("export declare const {name}: {{"));
        for (key, vname, raw) in &keys {
            out.doc("  ", self.ir.doc(&format!("{}.{vname}", e.name)));
            out.js(&format!("  {key}: {raw},"));
            out.dts(&format!("  readonly {key}: {name};"));
        }
        out.js("  name(v) {");
        out.js("    switch (v) {");
        for (_, vname, raw) in &keys {
            out.js(&format!("      case {raw}: return {};", js_str(vname)));
        }
        out.js("      default: return undefined;");
        out.js("    }");
        out.js("  },");
        out.dts("  /** The name of a declared value, or `undefined` for a value the schema does not declare. */");
        out.dts("  name(v: number): string | undefined;");
        out.js("});");
        out.dts("};");
        out.blank();
    }

    fn emit_struct(&self, out: &mut Out, s: &Struct) {
        let name = self.top_ident(&s.name);
        out.doc("", self.ir.doc(&s.name));
        out.dts(&format!("export interface {name} {{"));
        for (fname, ty) in &s.fields {
            let mut d = String::new();
            js_doc(&mut d, "  ", self.ir.doc(&format!("{}.{fname}", s.name)));
            out.dts.push_str(&d);
            out.dts(&format!("  readonly {fname}: {};", self.inline_ty(ty)));
        }
        out.dts("}");

        let cname = format!("_codec_{}", s.name);
        out.dts(&format!("export declare const {cname}: _graven.LeCodec<{name}>;"));
        out.js(&format!("export const {cname} = {{"));
        out.js(&format!("  size: {},", s.size));
        if s.fields.is_empty() {
            out.js("  read() { return Object.freeze({}); },");
            out.js("  write() {},");
        } else {
            out.js("  read(dv, off) {");
            out.js("    return Object.freeze({");
            let mut at = 0usize;
            for (fname, ty) in &s.fields {
                let w = self.ir.inline_size(ty).expect("struct field has fixed size") as usize;
                out.js(&format!("      {fname}: {}.read(dv, off + {at}),", self.codec(ty)));
                at += w;
            }
            out.js("    });");
            out.js("  },");
            out.js("  write(dv, off, v) {");
            let mut at = 0usize;
            for (fname, ty) in &s.fields {
                let w = self.ir.inline_size(ty).expect("struct field has fixed size") as usize;
                out.js(&format!("    {}.write(dv, off + {at}, v.{fname});", self.codec(ty)));
                at += w;
            }
            out.js("  },");
        }
        out.js("};");
        out.blank();
    }

    /// A union is a type only (the reader returns plain objects), so it lives in `.d.ts`.
    fn emit_union(&self, out: &mut Out, u: &Union) {
        let name = self.top_ident(&u.name);
        let name_v = self.top_ident(&format!("{}Verified", u.name));
        for (target_name, suffix) in [(&name, ""), (&name_v, "Verified")] {
            let mut d = String::new();
            js_doc(&mut d, "", self.ir.doc(&u.name));
            out.dts.push_str(&d);
            out.dts(&format!("export type {target_name} ="));
            for (vname, tag, tid) in &u.variants {
                let cty = self.table_path(*tid, suffix);
                out.dts(&format!(
                    "  | {{ readonly tag: {tag}; readonly variant: {}; readonly value: {cty} }}",
                    js_str(vname)
                ));
            }
            out.dts("  | { readonly tag: number; readonly variant: \"Unknown\" };");
            out.dts("");
        }
    }
}

pub(super) fn escape_with(raw: &str, used: &mut HashSet<String>) -> String {
    let mut name = raw.to_string();
    while used.contains(&name) {
        name.push('_');
    }
    used.insert(name.clone());
    name
}

pub(super) fn js_doc(out: &mut String, indent: &str, text: Option<&str>) {
    let Some(t) = text else { return };
    let safe = t.replace("*/", "*\\/");
    if !safe.contains('\n') {
        let _ = writeln!(out, "{indent}/** {safe} */");
    } else {
        let _ = writeln!(out, "{indent}/**");
        for l in safe.lines() {
            if l.is_empty() {
                let _ = writeln!(out, "{indent} *");
            } else {
                let _ = writeln!(out, "{indent} * {l}");
            }
        }
        let _ = writeln!(out, "{indent} */");
    }
}

pub(super) fn js_str(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_control() => {
                let _ = write!(out, "\\u{:04x}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

pub(super) fn upper_snake(s: &str) -> String {
    super::snake(s).to_ascii_uppercase()
}

fn is_bigint(p: Prim) -> bool {
    matches!(p, Prim::U64 | Prim::I64 | Prim::U128 | Prim::I128)
}

fn prim_ty(p: Prim) -> &'static str {
    if is_bigint(p) { "bigint" } else { "number" }
}

fn prim_codec(p: Prim) -> &'static str {
    match p {
        Prim::U8 => "_graven.leU8",
        Prim::U16 => "_graven.leU16",
        Prim::U32 => "_graven.leU32",
        Prim::U64 => "_graven.leU64",
        Prim::U128 => "_graven.leU128",
        Prim::I8 => "_graven.leI8",
        Prim::I16 => "_graven.leI16",
        Prim::I32 => "_graven.leI32",
        Prim::I64 => "_graven.leI64",
        Prim::I128 => "_graven.leI128",
        Prim::F32 => "_graven.leF32",
        Prim::F64 => "_graven.leF64",
    }
}

fn fmt_float(p: Prim, v: f64) -> String {
    match p {
        Prim::F32 => {
            let f = v as f32;
            if f == 0.0 && f.is_sign_negative() { "-0".to_string() } else { format!("{f:?}") }
        }
        _ => {
            if v == 0.0 && v.is_sign_negative() { "-0".to_string() } else { format!("{v:?}") }
        }
    }
}
