//! Names that would break the generated Rust (part of [`mod@crate::check`]).
//!
//! The codegen ([`crate::codegen`]) derives identifiers from schema names: types become a
//! `struct`/`enum` plus suffixes (`XVerified`, `XW`, `XE`, `XListW`, `UVerified`), the layout
//! module `x_snake` and the consts `X_UPPER_REQ`/`_MASK`/`_SCHEMA_ID`; fields become
//! methods (reader, view, writer, `<field>_streaming`, `<field>_<variant_snake>`) and layout
//! consts (`FIELD`, `FIELD_BIT`). This pass rejects, with a diagnostic, every name that:
//!
//! 1. is `self`, `Self`, `super`, `crate` or `_` (they cannot be raw identifiers `r#`); other
//!    Rust keywords are accepted as fields and variants and are emitted as
//!    `r#name`;
//! 2. is a type name that does not start with an uppercase letter `A–Z` (this rules out
//!    keywords, primitives like `str`/`usize`, a collision of the type with its own layout
//!    module and with local variables of the generated code), or whose layout module would be
//!    `self`/`super`/`crate` (`Crate`, `SELF`); other modules that are keywords
//!    (`Type` ⇒ `mod r#type`) are emitted as raw identifiers;
//! 3. is the enum variant `Unknown`, `from_raw` or `to_raw`, or the union variant `Unknown`;
//! 4. generates an identifier that collides with another one generated in the same scope: in the
//!    module (Rust's type and value namespaces, separately), in a table's layout
//!    module, and in the reader, view and writer methods of a table.
//!
//! Names like `Option`, `String` or `FnOnce` are accepted: the generated code only uses absolute
//! paths (`::core::…`, `::graven::…`) and lowercase primitives.

use std::collections::{HashMap, HashSet};

use crate::ast::{self, Item, Span, TypeRef};
use crate::codegen::snake;
use crate::ir::{Diag, Ty};

/// Rust words that cannot be raw identifiers.
const UNRAWABLE: [&str; 5] = ["self", "Self", "super", "crate", "_"];

/// Owner "the generated code itself" (fixed names).
const FIXED: &str = "the generated code";

fn upper(s: &str) -> String {
    snake(s).to_ascii_uppercase()
}

pub(crate) fn pascal(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for part in s.split('_').filter(|p| !p.is_empty()) {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.push(first.to_ascii_uppercase());
            out.extend(chars);
        }
    }
    if out.is_empty() {
        out.push_str(s);
    }
    out
}

/// A scope of generated names: name → (owner, description).
#[derive(Default)]
struct Scope {
    map: HashMap<String, (String, String)>,
}

struct Names<'a> {
    diags: &'a mut Vec<Diag>,
    /// Pairs of owners already reported (one collision per pair).
    reported: HashSet<(String, String)>,
}

impl Names<'_> {
    fn err(&mut self, span: Span, msg: String) {
        self.diags.push(Diag { span, msg });
    }

    fn add(&mut self, sc: &mut Scope, name: String, owner: &str, desc: &str, span: Span) {
        match sc.map.get(&name) {
            Some((o, d)) if o != owner => {
                if self.reported.insert((o.clone(), owner.to_string())) {
                    let msg = if o == FIXED {
                        format!("{owner} generates `{name}` ({desc}), which collides with `{name}` ({d}) of the generated code; rename it")
                    } else {
                        format!("{owner} generates `{name}` ({desc}), which collides with `{name}` generated by {o} ({d}); rename one of them")
                    };
                    self.err(span, msg);
                }
            }
            Some(_) => {}
            None => {
                sc.map.insert(name, (owner.to_string(), desc.to_string()));
            }
        }
    }

    /// Rule 1; `true` if the name is rejected.
    fn unrawable(&mut self, name: &str, what: &str, span: Span) -> bool {
        if UNRAWABLE.contains(&name) {
            self.err(
                span,
                format!("`{name}` cannot be the name of a {what}: it is a Rust keyword that cannot be a raw identifier (`r#`)"),
            );
            true
        } else {
            false
        }
    }
}

/// Shape of the field for the names the codegen generates.
enum Kind<'s> {
    Bool,
    Scalar,
    Ptr,
    List { streaming: bool },
    Union(&'s ast::UnionDecl),
    Unresolved,
}

/// Applies the module's rules; appends diagnostics to `diags`. `resolve` gives the type of
/// a name (built-in or declared).
pub(crate) fn check_names(s: &ast::Schema, resolve: &dyn Fn(&str) -> Option<Ty>, diags: &mut Vec<Diag>) {
    let mut nx = Names { diags, reported: HashSet::new() };
    let unions: HashMap<&str, &ast::UnionDecl> = s
        .items
        .iter()
        .filter_map(|i| match i {
            Item::Union(u) => Some((u.name.as_str(), u)),
            _ => None,
        })
        .collect();

    let has_rules = s.items.iter().any(|i| match i {
        Item::Table(t) => {
            t.attrs.iter().any(|a| a.name != "allow_breaking_readers")
                || t.fields.iter().any(|f| f.attrs.iter().any(|a| a.name != "allow_breaking_readers"))
        }
        _ => false,
    });
    let (mut types, mut values) = (Scope::default(), Scope::default());
    values.map.insert("SCHEMA_ID".into(), (FIXED.into(), "root schema id".into()));
    if has_rules {
        types.map.insert("Checks".into(), (FIXED.into(), "validation checks trait".into()));
    }
    let mut seen = HashSet::new();

    for item in &s.items {
        let (name, span) = match item {
            Item::Enum(e) => (&e.name, e.span),
            Item::Struct(d) => (&d.name, d.span),
            Item::Table(t) => (&t.name, t.span),
            Item::Union(u) => (&u.name, u.span),
            Item::Service(svc) => (&svc.name, svc.span),
        };
        // Duplicate already reported by `check`.
        if !seen.insert(name.as_str()) {
            continue;
        }
        let type_ok = type_name(&mut nx, name, span);

        match item {
            Item::Enum(e) => {
                for (v, _, sp) in &e.values {
                    if nx.unrawable(v, "variant", *sp) {
                        continue;
                    }
                    if matches!(v.as_str(), "Unknown" | "from_raw" | "to_raw") {
                        nx.err(
                            *sp,
                            format!(
                                "variant `{v}` of enum `{}` collides with the generated code (`{}::Unknown(raw)`, `from_raw`, `to_raw`); rename it",
                                e.name, e.name
                            ),
                        );
                    }
                }
            }
            Item::Struct(d) => {
                for (f, _, sp) in &d.fields {
                    nx.unrawable(f, "field", *sp);
                }
            }
            Item::Union(u) => {
                for (v, _, _, sp) in &u.variants {
                    if nx.unrawable(v, "variant", *sp) {
                        continue;
                    }
                    if v == "Unknown" {
                        nx.err(
                            *sp,
                            format!("variant `Unknown` of union `{}` collides with `{}::Unknown(tag)` of the generated code; rename it", u.name, u.name),
                        );
                    }
                }
            }
            Item::Table(t) => table_fields(&mut nx, t, resolve, &unions, has_rules),
            Item::Service(svc) => service_methods(&mut nx, svc),
        }

        if !type_ok {
            continue;
        }
        let owner = format!("`{name}`");
        let (k, sp) = (&owner, span);
        match item {
            Item::Enum(_) => nx.add(&mut types, name.clone(), k, "enum", sp),
            Item::Struct(_) => nx.add(&mut types, name.clone(), k, "struct", sp),
            Item::Union(_) => {
                nx.add(&mut types, name.clone(), k, "union", sp);
                nx.add(&mut types, format!("{name}Verified"), k, "verified-view union", sp);
                // Emitted only with `--side`, reserved always: adding a side must never make a
                // schema that compiled before stop compiling.
                nx.add(&mut types, format!("{name}W"), k, "RPC union writer", sp);
            }
            Item::Table(_) => {
                for (suffix, desc) in
                    [("", "reader"), ("Verified", "verified view"), ("W", "writer"), ("E", "element descriptor"), ("ListW", "list writer")]
                {
                    let n = format!("{name}{suffix}");
                    nx.add(&mut types, n.clone(), k, desc, sp);
                    // Tuple / unit struct: it also occupies the value namespace.
                    nx.add(&mut values, n, k, desc, sp);
                }
                nx.add(&mut types, snake(name), k, "layout module", sp);
                let up = upper(name);
                nx.add(&mut values, format!("{up}_REQ"), k, "required-fields const", sp);
                nx.add(&mut values, format!("{up}_MASK"), k, "mask const", sp);
                nx.add(&mut values, format!("{up}_SCHEMA_ID"), k, "schema id const", sp);
            }
            Item::Service(_) => {
                nx.add(&mut types, format!("{name}Call"), k, "service call enum", sp);
                nx.add(&mut types, format!("{name}Client"), k, "service client", sp);
                nx.add(&mut types, format!("{}_timeouts", snake(name)), k, "service timeouts module", sp);
                nx.add(&mut values, format!("{}_SERVICE_ID", upper(name)), k, "service id const", sp);
            }
        }
    }
}

/// Rules 1 and 2 for a type name; `true` if the name is accepted.
fn type_name(nx: &mut Names<'_>, name: &str, span: Span) -> bool {
    if nx.unrawable(name, "type", span) {
        return false;
    }
    if !name.starts_with(|c: char| c.is_ascii_uppercase()) {
        nx.err(
            span,
            format!(
                "type name `{name}` must start with an uppercase letter (A–Z): the generated code uses the name as a Rust type and derives the module `{}` from it",
                snake(name)
            ),
        );
        return false;
    }
    let m = snake(name);
    if UNRAWABLE.contains(&m.as_str()) {
        nx.err(span, format!("type `{name}` would generate the layout module `{m}`, which is not a valid Rust identifier; rename it"));
        return false;
    }
    true
}

fn field_kind<'s>(ty: &TypeRef, resolve: &dyn Fn(&str) -> Option<Ty>, unions: &HashMap<&str, &'s ast::UnionDecl>) -> Kind<'s> {
    match ty {
        TypeRef::List(inner) => {
            Kind::List { streaming: !matches!(&**inner, TypeRef::Named(n) if n == "string" || n == "bytes") }
        }
        TypeRef::Named(n) => match resolve(n) {
            Some(Ty::Bool) => Kind::Bool,
            Some(Ty::Scalar(_) | Ty::Enum(_) | Ty::Struct(_)) => Kind::Scalar,
            Some(Ty::Str | Ty::Bytes | Ty::Table(_) | Ty::List(_)) => Kind::Ptr,
            Some(Ty::Union(_)) => unions.get(n.as_str()).map_or(Kind::Unresolved, |u| Kind::Union(u)),
            None => Kind::Unresolved,
        },
    }
}

fn table_fields(
    nx: &mut Names<'_>,
    t: &ast::TableDecl,
    resolve: &dyn Fn(&str) -> Option<Ty>,
    unions: &HashMap<&str, &ast::UnionDecl>,
    has_rules: bool,
) {
    let mut layout = Scope::default();
    let (mut reader, mut view, mut writer) = (Scope::default(), Scope::default(), Scope::default());
    for c in ["FIXED_LEN", "PTR_SLOTS"] {
        layout.map.insert(c.into(), (FIXED.into(), "layout const".into()));
    }
    for m in ["SCHEMA_ID", "read", "verified", "verified_with", "from_bytes", "verify"] {
        reader.map.insert(m.into(), (FIXED.into(), "reader item".into()));
    }
    view.map.insert("reader".into(), (FIXED.into(), "view method".into()));
    for m in ["root", "to_bytes", "seal"] {
        writer.map.insert(m.into(), (FIXED.into(), "writer method".into()));
    }
    if has_rules {
        for m in ["validate", "validate_all", "validate_all_into"] {
            view.map.insert(m.into(), (FIXED.into(), "validation method".into()));
        }
        writer.map.insert("to_bytes_validated".into(), (FIXED.into(), "validation writer method".into()));
    }

    let mut seen = HashSet::new();
    for f in &t.fields {
        let Some(name) = &f.name else { continue };
        if !seen.insert(name.as_str()) || nx.unrawable(name, "field", f.span) {
            continue;
        }
        let owner = format!("field `{name}` of `{}`", t.name);
        let sp = f.span;
        let kind = f.ty.as_ref().map_or(Kind::Unresolved, |ty| field_kind(ty, resolve, unions));
        let up = upper(name);
        if !matches!(kind, Kind::Bool | Kind::Unresolved) {
            nx.add(&mut layout, up.clone(), &owner, "slot offset", sp);
        }
        if matches!(kind, Kind::Bool | Kind::Scalar) {
            nx.add(&mut layout, format!("{up}_BIT"), &owner, "presence bit", sp);
        }
        nx.add(&mut reader, name.clone(), &owner, "reader accessor", sp);
        nx.add(&mut view, name.clone(), &owner, "view accessor", sp);
        match kind {
            Kind::Union(u) => {
                for (v, _, _, _) in &u.variants {
                    let vo = format!("{owner} (variant `{v}`)");
                    nx.add(&mut writer, format!("{name}_{}", snake(v)), &vo, "writer variant setter", sp);
                }
            }
            Kind::List { streaming } => {
                nx.add(&mut writer, name.clone(), &owner, "writer setter", sp);
                if streaming {
                    nx.add(&mut writer, format!("{name}_streaming"), &owner, "writer streaming list", sp);
                }
            }
            _ => nx.add(&mut writer, name.clone(), &owner, "writer setter", sp),
        }
    }
}

fn service_methods(nx: &mut Names<'_>, svc: &ast::ServiceDecl) {
    let mut client = Scope::default();
    let mut call_enum = Scope::default();
    let mut timeouts = Scope::default();
    client.map.insert("new".into(), (FIXED.into(), "client constructor".into()));
    let mut seen = HashSet::new();
    for m in &svc.methods {
        let Some(name) = &m.name else { continue };
        if !seen.insert(name.as_str()) || nx.unrawable(name, "method", m.span) {
            continue;
        }
        let owner = format!("method `{name}` of service `{}`", svc.name);
        nx.add(&mut client, name.clone(), &owner, "client method", m.span);
        nx.add(&mut client, format!("{name}_with_timeout"), &owner, "client override method", m.span);
        nx.add(&mut call_enum, pascal(name), &owner, "call enum variant", m.span);
        nx.add(&mut timeouts, format!("{}_MS", upper(name)), &owner, "timeout const", m.span);
    }
}
